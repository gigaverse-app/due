"""Generated books proofs must detect moved inputs and wrong external results."""

import pytest
from pytest_obligation import contract_cases

from due.django.conformance._internal.immutable_inputs import admission_paths
from due.django.conformance.suite import effect_contract
from examples.books import search, services
from examples.books.effects import IndexBook, index_book, publish_book
from examples.books.models import Book, IndexBookWork
from integration_tests.conformance import test_book_contracts as generated
from integration_tests.conformance.book_examples import INDEX_EXAMPLES, PUBLISH_EXAMPLES

pytestmark = pytest.mark.django_db(transaction=True)


def test_generated_indexing_proof_rejects_retry_recapturing_changed_metadata(monkeypatch: pytest.MonkeyPatch) -> None:
    def recapture(book_id: int) -> bool:
        with index_book.atomic(book_id) as pending:
            owner = pending.locked_owner
            pending.request_work(IndexBookWork(title=owner.title, author=owner.author, universe="example"))
        return True

    monkeypatch.setattr(services, "retry_indexing", recapture)
    path = next(path for path in admission_paths(INDEX_EXAMPLES) if path.kind == "admission")
    with pytest.raises(AssertionError, match="immutable_inputs is false"):
        getattr(generated.TestBookIndexing(), "test_immutable_inputs_hold")(path)  # noqa: B009 - generated by the class decorator


def test_generated_publication_proof_rejects_settlement_replacing_captured_key(monkeypatch: pytest.MonkeyPatch) -> None:
    original = IndexBook.finalize_success

    def recapture(self: IndexBook, work: IndexBookWork, result: str) -> None:
        original(self, work, Book.objects.get(pk=work.owner_id).title)

    monkeypatch.setattr(IndexBook, "finalize_success", recapture)
    path = next(iter(admission_paths(PUBLISH_EXAMPLES)))
    with pytest.raises(AssertionError, match="immutable_inputs is false"):
        getattr(generated.TestBookPublication(), "test_immutable_inputs_hold")(path)  # noqa: B009 - generated by the class decorator


@pytest.mark.parametrize("publication", [False, True], ids=["indexing", "publication"])
def test_generated_books_replay_rejects_consistently_wrong_provider_result(
    monkeypatch: pytest.MonkeyPatch, publication: bool
) -> None:
    if publication:
        original_publish = search.publish

        def wrong_publication(key: str) -> str:
            original_publish(key)
            with search.connection() as connection:
                connection.execute("UPDATE books SET published=0 WHERE key=?", (key,))
            return key

        monkeypatch.setattr(search, "publish", wrong_publication)
    else:
        original_put = search.put

        def wrong_index(entry: search.IndexEntry) -> str:
            return original_put(entry.model_copy(update={"title": "wrong title"}))

        monkeypatch.setattr(search, "put", wrong_index)
    contract = (
        effect_contract(publish_book, examples=PUBLISH_EXAMPLES)
        if publication
        else effect_contract(index_book, examples=INDEX_EXAMPLES)
    )
    case = next(
        row.values[0] for row in contract_cases(contract) if row.id == "REPLAY_SAFE_EXECUTION-assert_replay_converges"
    )
    with pytest.raises(AssertionError, match="declared product outcome"):
        case.run()


def test_generated_terminal_proof_rejects_unpublished_index(monkeypatch):
    original = search.publish

    def hidden(key):
        result = original(key)
        with search.connection() as connection:
            connection.execute("UPDATE books SET published=0 WHERE key=?", (key,))
        return result

    monkeypatch.setattr(search, "publish", hidden)
    case = next(
        row.values[0]
        for row in contract_cases(effect_contract(index_book, examples=INDEX_EXAMPLES))
        if row.id.startswith("completion-")
    )
    with pytest.raises(AssertionError, match="terminal outcome"):
        case.run()
